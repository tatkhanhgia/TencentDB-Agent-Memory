#!/usr/bin/env bash
# Stdio MCP wrapper for MemoryMCP. Point any MCP harness's "command" here —
# env is owned by .mcp.env, so harness configs need no env block.
#
# MCP stdio protocol: NEVER write to stdout from this script; diagnostics
# go to stderr only.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
MCP_MAIN="$REPO_ROOT/MemoryMCP/bin/tdai-memory-mcp.mjs"

ENV_FILE="$SCRIPT_DIR/.mcp.env"
if [[ ! -f "$ENV_FILE" ]]; then
  echo "[tdai-memory-mcp] $ENV_FILE not found. cp .mcp.env.example .mcp.env and fill it in." >&2
  exit 1
fi
set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

# .mcp.env also carries HTTP-mode settings; force stdio for this wrapper.
unset TDAI_MCP_HTTP_PORT TDAI_MCP_HTTP_HOST TDAI_MCP_BINDINGS

# API key fallback: admin key generated by start-memory-core.sh
if [[ -z "${TDAI_API_KEY:-}" && -s "$SCRIPT_DIR/.admin-key" ]]; then
  TDAI_API_KEY="$(cat "$SCRIPT_DIR/.admin-key")"
  export TDAI_API_KEY
fi

# GUI-launched harnesses (Windsurf, Cursor) may not inherit a shell PATH.
find_node() {
  if command -v node >/dev/null 2>&1; then command -v node; return; fi
  for p in /usr/local/bin/node /opt/homebrew/bin/node; do
    [[ -x "$p" ]] && { echo "$p"; return; }
  done
  echo "[tdai-memory-mcp] node not found (need >= 20)" >&2
  exit 1
}
NODE="$(find_node)"

if [[ ! -f "$MCP_MAIN" ]]; then
  echo "[tdai-memory-mcp] $MCP_MAIN missing. Run: cd MemoryMCP && npm install && npm run build" >&2
  exit 1
fi

exec "$NODE" "$MCP_MAIN"
